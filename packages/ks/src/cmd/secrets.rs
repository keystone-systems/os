/// A file is a sops file if it carries sops metadata (the `mac` entry inside
/// the `sops` section). Cheap content heuristic — avoids parsing every
/// format sops supports.
fn is_sops_file(content: &str) -> bool {
    content.contains("sops") && (content.contains("mac:") || content.contains("\"mac\""))
}

fn collect_sops_files(dir: &Path, files: &mut Vec<PathBuf>) -> Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)
        .with_context(|| format!("Failed to read {}", dir.display()))?
        .collect::<std::io::Result<_>>()?;
    entries.sort_by_key(|entry| entry.file_name());

    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect_sops_files(&path, files)?;
        } else if let Ok(content) = std::fs::read_to_string(&path) {
            if is_sops_file(&content) {
                files.push(path);
            }
        }
    }
    Ok(())
}

async fn rekey(flake: Option<&Path>) -> Result<()> {
    sync(flake).await?;

    let repo_root = repo::find_repo(flake)?;
    let secrets_dir = repo_root.join("secrets");
    if !secrets_dir.is_dir() {
        bail!("No secrets/ directory at {}", repo_root.display());
    }

    let mut files = Vec::new();
    collect_sops_files(&secrets_dir, &mut files)?;
    if files.is_empty() {
        println!("No sops files found under {}", secrets_dir.display());
        return Ok(());
    }

    let mut failed = 0usize;
    for file in &files {
        println!("==> sops updatekeys {}", file.display());
        let mut cmd = Command::new("sops");
        cmd.args(["updatekeys", "--yes"])
            .arg(file)
            .current_dir(&repo_root);
        inject_yubikey_identity(&mut cmd);
        let status = cmd
            .status()
            .await
            .context("Failed to run sops — is it installed?")?;
        if !status.success() {
            eprintln!("FAIL {}", file.display());
            failed += 1;
        }
    }

    println!(
        "Rekeyed {} of {} sops files",
        files.len() - failed,
        files.len()
    );
    if failed > 0 {
        bail!("{} file(s) failed to rekey", failed);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_generated_sops_yaml() {
        let rules = vec![
            CreationRule {
                path_regex: "secrets/maia\\.yaml".to_string(),
                age: vec!["age1admin".to_string(), "age1host".to_string()],
            },
            CreationRule {
                path_regex: "secrets/shared\\.yaml".to_string(),
                age: vec!["age1admin".to_string()],
            },
        ];

        let rendered = render_sops_yaml(&rules);
        assert_eq!(
            rendered,
            "# GENERATED by 'ks secrets sync' — do not edit by hand.\n\
             creation_rules:\n\
             \x20 - path_regex: secrets/maia\\.yaml\n\
             \x20   age: age1admin,age1host\n\
             \x20 - path_regex: secrets/shared\\.yaml\n\
             \x20   age: age1admin\n"
        );
    }

    #[test]
    fn orders_file_groups_services_then_shared() {
        assert_eq!(file_group("secrets/services/k3s\\.yaml"), 0);
        assert_eq!(file_group("secrets/shared\\.yaml"), 1);
    }

    #[test]
    fn detects_sops_metadata() {
        assert!(is_sops_file("data: ENC\nsops:\n  mac: ENC[AES256_GCM]\n"));
        assert!(is_sops_file("{\"sops\": {\"mac\": \"ENC\"}}"));
        assert!(!is_sops_file("plain: yaml\n"));
    }

    #[test]
    fn escapes_regex_dots() {
        assert_eq!(escape_regex_literal("ks.systems"), "ks\\.systems");
        assert_eq!(escape_regex_literal("maia"), "maia");
    }
}
