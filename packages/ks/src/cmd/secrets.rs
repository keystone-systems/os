//! `ks secrets ...` — sops-based secrets management for the config repo.
//!
//! Secrets live in-repo under `secrets/` as sops-encrypted YAML files.
//! `.sops.yaml` at the repo root is generated (never hand-edited) from two
//! inputs:
//!
//! 1. `hosts.nix` — each host's `hostPublicKey` (ssh-ed25519) is converted
//!    to an age recipient via `ssh-to-age`.
//! 2. `secrets/recipients.nix` — admin recipients (age/yubikey identities or
//!    ssh-ed25519 user keys) plus per-file host lists for non-per-host files.
//!
//! Every creation rule gets all admin recipients. `secrets/<host>.yaml`
//! additionally gets that host's recipient; entries in `recipients.nix`
//! `files` add host lists for shared/service files.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{anyhow, bail, Context, Result};
use clap::Subcommand;
use serde::Deserialize;
use tokio::process::Command;

use crate::repo;

#[derive(Subcommand)]
pub enum SecretsCommand {
    /// Edit a sops-encrypted file (uses the YubiKey age identity when present).
    Edit {
        /// File to edit, relative to the current directory or the repo root.
        file: PathBuf,
    },

    /// Regenerate .sops.yaml, then re-encrypt every sops file under secrets/
    /// for the current recipient set (`sops updatekeys`).
    Rekey,

    /// Regenerate .sops.yaml from hosts.nix and secrets/recipients.nix.
    Sync,

    /// Issue short-TTL credentials (runbook only — not implemented).
    Issue,

    /// Apply sops-encrypted k8s manifests (runbook only — not implemented).
    Apply,
}

pub async fn execute(cmd: SecretsCommand, flake: Option<&Path>) -> Result<()> {
    match cmd {
        SecretsCommand::Edit { file } => edit(&file, flake).await,
        SecretsCommand::Rekey => rekey(flake).await,
        SecretsCommand::Sync => sync(flake).await,
        SecretsCommand::Issue => stub("issue", "issued-credential runbooks"),
        SecretsCommand::Apply => stub("apply", "the k8s apply runbook"),
    }
}

fn stub(name: &str, runbook: &str) -> Result<()> {
    bail!(
        "`ks secrets {}` is not implemented yet — see docs/SECRETS.md for {}.",
        name,
        runbook
    )
}

// ---------------------------------------------------------------------------
// edit
// ---------------------------------------------------------------------------

/// Path (under $HOME) of the age-plugin-yubikey identity file written by
/// `keystone.terminal.ageYubikey`.
const YUBIKEY_IDENTITY_RELATIVE: &str = ".age/yubikey-identity.txt";

/// Prefer the YubiKey age identity for sops when the caller has not already
/// chosen one: set SOPS_AGE_KEY_FILE to ~/.age/yubikey-identity.txt when the
/// env var is unset and the file exists. Shared by `edit` and `rekey` so the
/// two paths cannot drift.
fn inject_yubikey_identity(cmd: &mut Command) {
    if std::env::var_os("SOPS_AGE_KEY_FILE").is_none() {
        if let Some(identity) = home::home_dir().map(|home| home.join(YUBIKEY_IDENTITY_RELATIVE)) {
            if identity.is_file() {
                cmd.env("SOPS_AGE_KEY_FILE", &identity);
            }
        }
    }
}

async fn edit(file: &Path, flake: Option<&Path>) -> Result<()> {
    let repo_root = repo::find_repo(flake)?;
    let target = if file.exists() {
        // Absolute, since sops runs with current_dir at the repo root below.
        std::fs::canonicalize(file)
            .with_context(|| format!("Failed to resolve {}", file.display()))?
    } else {
        let in_repo = repo_root.join(file);
        if in_repo.exists() {
            in_repo
        } else if file
            .strip_prefix(&repo_root)
            .unwrap_or(file)
            .starts_with("secrets")
        {
            // New file under secrets/: let sops create it via the .sops.yaml
            // creation rules (run from the repo root so path_regex matches).
            in_repo
        } else {
            bail!(
                "File not found: {} (also tried {}; new files can only be created under secrets/)",
                file.display(),
                in_repo.display()
            );
        }
    };

    let mut cmd = Command::new("sops");
    cmd.arg(&target);
    cmd.current_dir(&repo_root);
    inject_yubikey_identity(&mut cmd);

    let status = cmd
        .status()
        .await
        .context("Failed to run sops — is it installed?")?;
    if !status.success() {
        std::process::exit(status.code().unwrap_or(1));
    }
    Ok(())
}

