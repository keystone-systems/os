const SOPS_YAML_HEADER: &str = "# GENERATED by 'ks secrets sync' — do not edit by hand.";

#[derive(Debug, Deserialize)]
struct Recipients {
    /// Admin recipients: age/yubikey identities used verbatim, ssh-ed25519
    /// entries converted via ssh-to-age.
    admins: BTreeMap<String, String>,
    /// path_regex → host list for non-per-host files.
    #[serde(default)]
    files: BTreeMap<String, FileRecipients>,
}

#[derive(Debug, Deserialize)]
struct FileRecipients {
    hosts: Vec<String>,
}

#[derive(Debug)]
struct CreationRule {
    path_regex: String,
    age: Vec<String>,
}

async fn nix_eval_file(path: &Path) -> Result<serde_json::Value> {
    let output = Command::new("nix")
        .args(["eval", "--json", "--file"])
        .arg(path)
        .output()
        .await
        .with_context(|| format!("Failed to evaluate {}", path.display()))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!("Failed to evaluate {}: {}", path.display(), stderr.trim());
    }

    serde_json::from_slice(&output.stdout)
        .with_context(|| format!("Failed to parse output of nix eval {}", path.display()))
}

/// Convert an ssh-ed25519 public key to an age recipient via `ssh-to-age`.
async fn ssh_to_age(public_key: &str) -> Result<String> {
    use tokio::io::AsyncWriteExt;

    let mut child = Command::new("ssh-to-age")
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .context("Failed to run ssh-to-age — is it installed?")?;

    child
        .stdin
        .take()
        .expect("stdin was piped")
        .write_all(format!("{}\n", public_key).as_bytes())
        .await
        .context("Failed to write to ssh-to-age stdin")?;

    let output = child
        .wait_with_output()
        .await
        .context("Failed to wait for ssh-to-age")?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        bail!("ssh-to-age failed for '{}': {}", public_key, stderr.trim());
    }

    let recipient = String::from_utf8_lossy(&output.stdout).trim().to_string();
    if !recipient.starts_with("age1") {
        bail!(
            "ssh-to-age produced unexpected output for '{}': {}",
            public_key,
            recipient
        );
    }
    Ok(recipient)
}

/// Resolve a recipients.nix admin entry to an age recipient. `age1...`
/// entries (including age-plugin-yubikey recipients) pass through verbatim.
async fn admin_recipient(name: &str, value: &str) -> Result<String> {
    if value.starts_with("age1") {
        Ok(value.to_string())
    } else if value.starts_with("ssh-ed25519 ") {
        ssh_to_age(value).await
    } else {
        bail!(
            "Unsupported admin recipient '{}' in secrets/recipients.nix: expected an age1... or ssh-ed25519 value",
            name
        )
    }
}

fn escape_regex_literal(value: &str) -> String {
    value.replace('.', "\\.")
}

/// Read `hostPublicKey` per host from hosts.nix and convert to age recipients.
async fn host_age_recipients(hosts_nix: &Path) -> Result<BTreeMap<String, String>> {
    let hosts = nix_eval_file(hosts_nix).await?;
    let hosts = hosts
        .as_object()
        .ok_or_else(|| anyhow!("hosts.nix did not evaluate to an attrset"))?;

    let mut recipients = BTreeMap::new();
    for (host, info) in hosts {
        let Some(public_key) = info
            .get("hostPublicKey")
            .and_then(|value| value.as_str())
            .filter(|value| !value.is_empty())
        else {
            continue;
        };
        recipients.insert(host.clone(), ssh_to_age(public_key).await?);
    }
    Ok(recipients)
}

/// Group index for creation-rule ordering: per-host files alphabetically,
/// then services, then shared (everything else).
fn file_group(path_regex: &str) -> u8 {
    if path_regex.starts_with("secrets/services/") {
        0
    } else {
        1
    }
}

async fn build_creation_rules(repo_root: &Path) -> Result<Vec<CreationRule>> {
    let hosts_nix = repo_root.join("hosts.nix");
    if !hosts_nix.is_file() {
        bail!(
            "ks secrets sync requires hosts.nix at the repo root ({})",
            repo_root.display()
        );
    }
    let recipients_nix = repo_root.join("secrets/recipients.nix");
    if !recipients_nix.is_file() {
        bail!(
            "ks secrets sync requires secrets/recipients.nix ({})",
            recipients_nix.display()
        );
    }

    let host_recipients = host_age_recipients(&hosts_nix).await?;
    let recipients: Recipients = serde_json::from_value(nix_eval_file(&recipients_nix).await?)
        .context(
            "Unexpected shape in secrets/recipients.nix (want { admins; files.<regex>.hosts; })",
        )?;

    let mut admin_recipients = Vec::with_capacity(recipients.admins.len());
    for (name, value) in &recipients.admins {
        admin_recipients.push(admin_recipient(name, value).await?);
    }

    let host_recipient = |host: &str| -> Result<String> {
        host_recipients.get(host).cloned().ok_or_else(|| {
            anyhow!(
                "Host '{}' referenced in secrets/recipients.nix has no hostPublicKey in hosts.nix",
                host
            )
        })
    };

    // Per-host files: every host with a hostPublicKey, alphabetically.
    let mut rules = Vec::new();
    for (host, recipient) in &host_recipients {
        let mut age = admin_recipients.clone();
        age.push(recipient.clone());
        rules.push(CreationRule {
            path_regex: format!("secrets/{}\\.yaml", escape_regex_literal(host)),
            age,
        });
    }

    // files entries: services, then shared; alphabetical within each group
    // (BTreeMap iteration is already sorted by pattern).
    let mut file_rules: Vec<(u8, CreationRule)> = Vec::new();
    for (path_regex, entry) in &recipients.files {
        let mut age = admin_recipients.clone();
        for host in &entry.hosts {
            age.push(host_recipient(host)?);
        }
        file_rules.push((
            file_group(path_regex),
            CreationRule {
                path_regex: path_regex.clone(),
                age,
            },
        ));
    }
    file_rules.sort_by(|a, b| (a.0, &a.1.path_regex).cmp(&(b.0, &b.1.path_regex)));
    rules.extend(file_rules.into_iter().map(|(_, rule)| rule));

    Ok(rules)
}

fn render_sops_yaml(rules: &[CreationRule]) -> String {
    let mut out = String::new();
    out.push_str(SOPS_YAML_HEADER);
    out.push_str("\ncreation_rules:\n");
    for rule in rules {
        out.push_str(&format!("  - path_regex: {}\n", rule.path_regex));
        out.push_str(&format!("    age: {}\n", rule.age.join(",")));
    }
    out
}

async fn sync(flake: Option<&Path>) -> Result<()> {
    let repo_root = repo::find_repo(flake)?;
    let rules = build_creation_rules(&repo_root).await?;
    let sops_yaml = repo_root.join(".sops.yaml");
    tokio::fs::write(&sops_yaml, render_sops_yaml(&rules))
        .await
        .with_context(|| format!("Failed to write {}", sops_yaml.display()))?;
    println!(
        "Wrote {} ({} creation rules)",
        sops_yaml.display(),
        rules.len()
    );
    Ok(())
}

